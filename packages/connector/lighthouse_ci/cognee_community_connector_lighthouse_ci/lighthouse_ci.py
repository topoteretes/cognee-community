"""DLT source for Lighthouse CI audit reports.

Reads and normalizes Lighthouse Result (LHR) JSON files generated by `lhci collect`
or Lighthouse CLI into searchable Cognee documents.

Extracts category scores (performance, accessibility, best-practices, SEO, PWA),
Core Web Vitals (LCP, FCP, TBT, CLS, Speed Index), and actionable failed audits /
opportunities while stripping bulky traces and screenshots.

Declared with document-mode metadata (DOCUMENT_SOURCE_ATTR = "lighthouse_ci"),
routing audit records through cognify rather than relational table schemas.
"""

from __future__ import annotations

import hashlib
import json
import logging
from pathlib import Path
import re
from typing import Any
from urllib.parse import parse_qsl, urlencode, urlparse, urlunparse

try:
    from cognee.shared.logging_utils import get_logger
    logger = get_logger("lighthouse_ci_connector")
except ImportError:
    logger = logging.getLogger("lighthouse_ci_connector")

try:
    from cognee.tasks.ingestion.dlt_utils import DOCUMENT_SOURCE_ATTR
except ImportError:
    DOCUMENT_SOURCE_ATTR = "cognee_document_source"

LIGHTHOUSE_CI_SOURCE_NAME = "lighthouse_ci"
LIGHTHOUSE_CI_TABLE_NAME = "lighthouse_ci_reports"

_SENSITIVE_PARAM_REGEX = re.compile(
    r"^(token|key|api_key|auth|password|secret|session|session_id|sig|signature)$",
    re.IGNORECASE,
)

CORE_METRIC_AUDITS = (
    "largest-contentful-paint",
    "first-contentful-paint",
    "total-blocking-time",
    "cumulative-layout-shift",
    "speed-index",
    "server-response-time",
    "interactive",
)


def sanitize_url(raw_url: str) -> str:
    """Sanitize URL by masking sensitive query parameters (token, key, auth)."""
    if not raw_url or not isinstance(raw_url, str):
        return ""
    try:
        parsed = urlparse(raw_url)
        if not parsed.query:
            return raw_url
        query_pairs = parse_qsl(parsed.query, keep_blank_values=True)
        sanitized_pairs = [
            (k, "[REDACTED]" if _SENSITIVE_PARAM_REGEX.match(k) else v)
            for k, v in query_pairs
        ]
        sanitized_query = urlencode(sanitized_pairs)
        return urlunparse(parsed._replace(query=sanitized_query))
    except Exception:
        return raw_url


def parse_lighthouse_report(
    report_data: dict[str, Any] | str | Path,
) -> dict[str, Any]:
    """Parse and validate a Lighthouse Result (LHR) JSON payload into structured report data."""
    if isinstance(report_data, (str, Path)):
        path = Path(report_data)
        if path.exists() and path.is_file():
            content = path.read_text(encoding="utf-8")
            try:
                lhr = json.loads(content)
            except json.JSONDecodeError as exc:
                raise ValueError(f"Report file '{path}' is not valid JSON: {exc}") from exc
        else:
            try:
                lhr = json.loads(str(report_data))
            except json.JSONDecodeError as exc:
                raise ValueError(f"Input report string is not valid JSON: {exc}") from exc
    elif isinstance(report_data, dict):
        lhr = report_data
    else:
        raise ValueError("report_data must be a dict, filepath, or JSON string.")

    # Validate essential LHR schema
    if not isinstance(lhr, dict):
        raise ValueError("Lighthouse report root must be a JSON object.")

    lh_version = lhr.get("lighthouseVersion", "unknown")
    fetch_time = lhr.get("fetchTime", "")
    requested_url = lhr.get("requestedUrl") or lhr.get("finalUrl") or lhr.get("finalDisplayedUrl", "")
    final_url = lhr.get("finalDisplayedUrl") or lhr.get("finalUrl") or requested_url

    if not requested_url and not final_url:
        raise ValueError("Lighthouse report missing requestedUrl or finalDisplayedUrl.")

    clean_url = sanitize_url(final_url or requested_url)

    # Extract category scores (scaled 0 - 100)
    categories_raw = lhr.get("categories") or {}
    categories: dict[str, dict[str, Any]] = {}
    for cat_id, cat_info in categories_raw.items():
        if isinstance(cat_info, dict):
            score = cat_info.get("score")
            score_val = int(round(score * 100)) if score is not None else None
            categories[cat_id] = {
                "title": cat_info.get("title", cat_id.capitalize()),
                "score": score_val,
            }

    # Extract performance metrics
    audits_raw = lhr.get("audits") or {}
    metrics: dict[str, dict[str, Any]] = {}
    for audit_id in CORE_METRIC_AUDITS:
        audit_info = audits_raw.get(audit_id)
        if isinstance(audit_info, dict):
            metrics[audit_id] = {
                "title": audit_info.get("title", audit_id),
                "display_value": audit_info.get("displayValue", ""),
                "score": audit_info.get("score"),
                "numeric_value": audit_info.get("numericValue"),
            }

    # Extract actionable findings & opportunities (score < 0.9 or explicit savings)
    findings: list[dict[str, Any]] = []
    for audit_id, audit_info in audits_raw.items():
        if not isinstance(audit_info, dict) or audit_id in CORE_METRIC_AUDITS:
            continue
        score = audit_info.get("score")
        details = audit_info.get("details") or {}
        is_opportunity = details.get("type") == "opportunity"
        # Only capture actionable issues (failures, warnings, or performance savings)
        if is_opportunity or (score is not None and score < 0.9):
            display_val = audit_info.get("displayValue", "")
            findings.append({
                "id": audit_id,
                "title": audit_info.get("title", audit_id),
                "description": audit_info.get("description", "").split("[Learn more]")[0].strip(),
                "score": score,
                "display_value": display_val,
                "is_opportunity": is_opportunity,
            })

    # Sort findings: opportunities first, then lowest score
    findings.sort(key=lambda f: (not f["is_opportunity"], f["score"] if f["score"] is not None else 1.0))

    # Generate deterministic report ID
    id_source = f"{clean_url}|{fetch_time}|{lh_version}"
    report_id = f"lh_{hashlib.sha256(id_source.encode('utf-8')).hexdigest()[:16]}"

    return {
        "report_id": report_id,
        "clean_url": clean_url,
        "fetch_time": fetch_time,
        "lighthouse_version": lh_version,
        "categories": categories,
        "metrics": metrics,
        "findings": findings[:20],  # Keep top 20 actionable findings to avoid bloat
    }


def format_lighthouse_report_markdown(
    report: dict[str, Any],
    build_id: str | None = None,
    commit_sha: str | None = None,
) -> str:
    """Format structured Lighthouse report data into a searchable markdown document."""
    url = report.get("clean_url", "")
    fetch_time = report.get("fetch_time", "")
    lh_version = report.get("lighthouse_version", "")
    categories = report.get("categories", {})
    metrics = report.get("metrics", {})
    findings = report.get("findings", [])

    lines = [
        f"# [Lighthouse CI] Audit Report: {url}",
        "",
        f"- **Audited URL:** {url}",
        f"- **Audit Timestamp:** {fetch_time}",
        f"- **Lighthouse Engine Version:** {lh_version}",
    ]
    if build_id:
        lines.append(f"- **Build ID:** {build_id}")
    if commit_sha:
        lines.append(f"- **Commit SHA:** {commit_sha}")

    # Categories section
    if categories:
        lines.extend(["", "## Category Scores"])
        for cat_id, cat_info in categories.items():
            score_str = f"{cat_info['score']} / 100" if cat_info["score"] is not None else "N/A"
            lines.append(f"- **{cat_info['title']}:** {score_str}")

    # Core Web Vitals & Metrics section
    if metrics:
        lines.extend(["", "## Core Web Vitals & Performance Metrics"])
        for metric_id, metric_info in metrics.items():
            display_val = metric_info.get("display_value") or "N/A"
            score = metric_info.get("score")
            score_str = f" (Score: {score:.2f})" if score is not None else ""
            lines.append(f"- **{metric_info['title']}:** {display_val}{score_str}")

    # Actionable findings section
    if findings:
        lines.extend(["", "## Top Actionable Findings & Diagnostic Opportunities"])
        for finding in findings:
            title = finding.get("title", "")
            fid = finding.get("id", "")
            desc = finding.get("description", "")
            display = finding.get("display_value", "")
            score = finding.get("score")
            savings_note = f" — *{display}*" if display else ""
            score_note = f" [Score: {score:.2f}]" if score is not None else ""
            lines.append(f"### {title} (`{fid}`){savings_note}{score_note}")
            if desc:
                lines.append(desc)
            lines.append("")

    return "\n".join(lines).strip()


def lighthouse_ci_source(
    reports_dir: str | Path | None = None,
    report_files: list[str | Path] | None = None,
    build_id: str | None = None,
    commit_sha: str | None = None,
):
    """Create a dlt source yielding Lighthouse CI audit reports as searchable documents.

    Args:
        reports_dir: Directory containing Lighthouse Result JSON files (e.g. `.lighthouseci/`).
        report_files: Explicit list of filepaths to Lighthouse Result JSON files.
        build_id: Optional CI/CD build identifier to attach to reports.
        commit_sha: Optional git commit SHA to attach to reports.

    Returns:
        A dlt source configured for Cognee document ingestion.
    """
    try:
        import dlt
    except ImportError as exc:
        raise ImportError(
            'The Lighthouse CI connector requires dlt: pip install "cognee-community-connector-lighthouse-ci" '
            'or pip install "dlt[sqlalchemy]".'
        ) from exc

    resolved_files: list[Path] = []
    if report_files:
        for rf in report_files:
            p = Path(rf)
            if p.exists() and p.is_file():
                resolved_files.append(p)
            else:
                logger.warning("Lighthouse CI: Specified file '%s' does not exist; skipping.", rf)

    if reports_dir:
        p_dir = Path(reports_dir)
        if p_dir.exists() and p_dir.is_dir():
            # Match standard Lighthouse CI filenames: lhr-*.json, manifest.json is excluded
            for child in p_dir.glob("*.json"):
                if child.name != "manifest.json":
                    resolved_files.append(child)
        else:
            logger.warning("Lighthouse CI: Directory '%s' does not exist.", reports_dir)

    if not resolved_files:
        raise ValueError(
            "No valid Lighthouse CI report files found. Pass reports_dir= or report_files=."
        )

    @dlt.resource(name=LIGHTHOUSE_CI_TABLE_NAME, primary_key="id", write_disposition="merge")
    def lighthouse_reports():
        yielded = 0
        for report_file in resolved_files:
            try:
                parsed = parse_lighthouse_report(report_file)
            except Exception as exc:
                logger.warning(
                    "Lighthouse CI: Failed to parse report '%s' (%s); skipping.",
                    report_file.name,
                    exc,
                )
                continue

            content = format_lighthouse_report_markdown(
                parsed, build_id=build_id, commit_sha=commit_sha
            )
            row = {
                "id": parsed["report_id"],
                "url": parsed["clean_url"],
                "title": f"[Lighthouse CI] {parsed['clean_url']} ({parsed['fetch_time']})",
                "fetch_time": parsed["fetch_time"],
                "lighthouse_version": parsed["lighthouse_version"],
                "performance_score": (parsed["categories"].get("performance") or {}).get("score"),
                "accessibility_score": (parsed["categories"].get("accessibility") or {}).get("score"),
                "best_practices_score": (parsed["categories"].get("best-practices") or {}).get("score"),
                "seo_score": (parsed["categories"].get("seo") or {}).get("score"),
                "build_id": build_id or "",
                "commit_sha": commit_sha or "",
                "content": content,
            }
            yielded += 1
            yield row

        logger.info("Lighthouse CI: Yielded %d report document(s).", yielded)

    @dlt.source(name=LIGHTHOUSE_CI_SOURCE_NAME)
    def _lighthouse():
        return lighthouse_reports

    source = _lighthouse()
    setattr(source, DOCUMENT_SOURCE_ATTR, LIGHTHOUSE_CI_SOURCE_NAME)
    return source
